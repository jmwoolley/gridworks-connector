"""Generate review artifacts. This is NOT the GridWorks Sema generator."""

import json
from pathlib import Path

from custom_components.gridworks_connector.protocol import Message, PAYLOADS
from custom_components.gridworks_connector.const import PREFIX

root = Path(__file__).resolve().parents[1]
out = root / "docs" / "proposed-sema"
out.mkdir(parents=True, exist_ok=True)
for kind, model in PAYLOADS.items():
    schema = Message.model_json_schema(by_alias=True)
    body = model.model_json_schema(by_alias=True)
    schema.setdefault("$defs", {}).update(body.pop("$defs", {}))
    schema["properties"]["TypeName"] = {"const": PREFIX + kind, "type": "string"}
    schema["properties"]["Payload"] = body
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["title"] = PREFIX + kind
    schema["description"] = "PROPOSED: not registered or generated by GridWorks Sema."
    (out / f"{PREFIX}{kind}.000.schema.json").write_text(
        json.dumps(schema, indent=2) + "\n", encoding="utf-8"
    )
print(f"Generated {len(PAYLOADS)} proposed review schemas")
